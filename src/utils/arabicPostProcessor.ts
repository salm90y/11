/**
 * حساب مسافة ليفنشتاين لتقييم مدى تقارب الكلمتين المشوهة والمقترحة
 */
export function levenshteinDistance(a: string, b: string): number {
  const tmp: number[][] = [];
  for (let i = 0; i <= a.length; i++) {
    tmp[i] = [i];
  }
  for (let j = 0; j <= b.length; j++) {
    tmp[0][j] = j;
  }
  for (let i = 1; i <= a.length; i++) {
    for (let j = 1; j <= b.length; j++) {
      tmp[i][j] = Math.min(
        tmp[i - 1][j] + 1,
        tmp[i][j - 1] + 1,
        tmp[i - 1][j - 1] + (a[i - 1] === b[j - 1] ? 0 : 1)
      );
    }
  }
  return tmp[a.length][b.length];
}

/**
 * البحث في القاموس عن الكلمة الأكثر شبهاً مع نسبة تطابق محددة
 */
export function getClosestDictionaryWord(word: string, threshold: number = 0.72): string | null {
  let bestWord: string | null = null;
  let bestSim = 0;

  for (const dictWord of ARABIC_DICTIONARY) {
    const distance = levenshteinDistance(word, dictWord);
    const maxLen = Math.max(word.length, dictWord.length);
    if (maxLen === 0) continue;
    const sim = 1 - distance / maxLen;

    if (sim > bestSim && sim >= threshold) {
      bestSim = sim;
      bestWord = dictWord;
    }
  }

  return bestWord;
}

/**
 * تصحيح الكلمة الفردية باستخدام عزل السوابق واللواحق والقاموس المورفولوجي
 */
export function correctSingleWord(word: string): string {
  // تنظيف الكلمة من أي رموز أو علامات ترقيم جانبية لاستخلاص الكلمة الصافية
  const cleanWord = word.replace(/[^\u0600-\u06FF]/g, "");
  if (cleanWord.length <= 2) return word;

  // 1. إذا كانت الكلمة موجودة في القاموس صراحة
  if (ARABIC_DICTIONARY.has(cleanWord)) {
    return word;
  }

  // 2. محاولة تجريد السوابق واللواحق
  let detectedPrefix = "";
  let detectedSuffix = "";
  let stem = cleanWord;

  // فحص السوابق
  for (const pref of ARABIC_PREFIXES) {
    if (cleanWord.startsWith(pref) && cleanWord.length - pref.length >= 3) {
      detectedPrefix = pref;
      stem = cleanWord.substring(pref.length);
      break;
    }
  }

  // فحص اللواحق على الجذع المتبقي
  for (const suff of ARABIC_SUFFIXES) {
    if (stem.endsWith(suff) && stem.length - suff.length >= 3) {
      detectedSuffix = suff;
      stem = stem.substring(0, stem.length - suff.length);
      break;
    }
  }

  // إذا كان الجذع المجرد صحيحاً وصريحاً في القاموس
  if (ARABIC_DICTIONARY.has(stem)) {
    let reconstructed = detectedPrefix + stem + detectedSuffix;
    if (reconstructed.endsWith("يي")) {
      reconstructed = reconstructed.substring(0, reconstructed.length - 1);
    }
    return word.replace(cleanWord, reconstructed);
  }

  // إذا وجدنا جذعاً قريباً جداً في القاموس للجذع المجرد
  const matchedStem = getClosestDictionaryWord(stem, 0.70);
  if (matchedStem) {
    let reconstructed = detectedPrefix + matchedStem + detectedSuffix;
    if (reconstructed.endsWith("يي")) {
      reconstructed = reconstructed.substring(0, reconstructed.length - 1);
    }
    return word.replace(cleanWord, reconstructed);
  }

  // 3. مطابقة الكلمة الصافية بالكامل مع كلمات القاموس الكاملة
  const matchedFullWord = getClosestDictionaryWord(cleanWord, 0.74);
  if (matchedFullWord) {
    return word.replace(cleanWord, matchedFullWord);
  }

  return word;
}

/**
 * معالجة وتصحيح طاطويل الحروف (الكشيدة ـــ) التي يقرؤها OCR بشكل خاطئ كـ "س" أو "سس" أو "يس" أو "نس" أو "سا"
 */
export function fixTatweelAndFalseSeen(text: string): string {
  if (!text) return "";

  let result = text;

  // كلمة "تاريخ" عند تطويل حرف التاء
  result = result.replace(/\bتساريخ\b/g, 'تاريخ');
  result = result.replace(/\bتسااريخ\b/g, 'تاريخ');
  result = result.replace(/\bتسارسيخ\b/g, 'تاريخ');

  // كلمة "المحال" عند تطويل حرف الحاء
  result = result.replace(/\bالمحسال\b/g, 'المحال');
  result = result.replace(/\bالمحسالة\b/g, 'المحالة');

  // كلمة "إلى" أو "على" عند تطويل حرف اللام/الياء
  result = result.replace(/\bالسى\b/g, 'إلى');
  result = result.replace(/\bعلسى\b/g, 'على');
  result = result.replace(/\bعلسي\b/g, 'علي');

  // كلمة "تقيده" عند تطويل حرف الياء/القاف
  result = result.replace(/\bتقيسده\b/g, 'تقيده');
  result = result.replace(/\bتقسيده\b/g, 'تقيده');

  // كلمة "المهني" عند تطويل حرف النون/الهاء
  result = result.replace(/\bالمهنسي\b/g, 'المهني');
  result = result.replace(/\bالمهنسية\b/g, 'المهنية');

  // كلمة "حسين" عند تطويل حرف السين/الياء
  result = result.replace(/\bحس ين\b/g, 'حسين');
  result = result.replace(/\bحسسين\b/g, 'حسين');

  // تصحيح الأفعال والأسماء الرسمية المبدوءة بـ "تس" بسبب مد الحرف
  const tatweelPrefixes: [RegExp, string][] = [
    [/\bتسنسيب\b/g, 'تنسيب'],
    [/\bتسدريب\b/g, 'تدريب'],
    [/\bتسعيين\b/g, 'تعيين'],
    [/\bتسكليف\b/g, 'تكليف'],
    [/\bترسفيع\b/g, 'ترفيع'],
    [/\bتسشكيل\b/g, 'تشكيل'],
    [/\bتسوجيه\b/g, 'توجيه'],
    [/\bتصسفيات\b/g, 'تصفيات'],
    [/\bتستدقيق\b/g, 'تدقيق'],
    [/\bتسطوير\b/g, 'تطوير'],
    [/\bتسوقيع\b/g, 'توقيع'],
    [/\bتسهنيئة\b/g, 'تهنئة'],
    [/\bتسرفيع\b/g, 'ترفيع'],
    [/\bتسصدير\b/g, 'تصدير'],
    [/\bتستثبيت\b/g, 'تثبيت'],
    [/\bتسبديل\b/g, 'تبديل'],
  ];

  for (const [pattern, repl] of tatweelPrefixes) {
    result = result.replace(pattern, repl);
  }

  // تصحيح التكرار الخاطئ لـ "س" وسط الكلمة
  result = result.replace(/([\u0600-\u06FF])س{3,}([\u0600-\u06FF])/g, '$1$2');

  return result;
}

/**
 * تجميع الحروف العربية المفككة داخل الكلمات (مثل: بقواع د -> بقواعد ، حس ين -> حسين)
 */
export function fixDisjointedLetters(text: string): string {
  if (!text) return "";

  let lines = text.split('\n');
  let fixedLines = lines.map(line => {
    // دمج الحروف المنفصلة بمسافة واحدة
    let l = line.replace(/(?:\b[\u0600-\u06FF]\b\s+){1,}\b[\u0600-\u06FF]\b/g, match => {
      return match.replace(/\s+/g, '');
    });

    // دمج الحروف الأخيرة المقطوعة
    l = l.replace(/\bبقواع\s+د\b/g, 'بقواعد');
    l = l.replace(/\bحس\s+ين\b/g, 'حسين');
    l = l.replace(/\bقوا\s+عد\b/g, 'قواعد');
    l = l.replace(/\bانف\s+كاك\b/g, 'انفكاك');
    l = l.replace(/\bتقا\s+عد\b/g, 'تقاعد');

    return l;
  });

  return fixedLines.join('\n');
}

/**
 * فك دمج الأسماء والكلمات الملتصقة بدون مسافة (مثل: كاملجابرشمخي -> كامل جابر شمخي)
 */
export function fixMergedWords(text: string): string {
  if (!text) return "";

  let result = text;

  // فك دمج الأسماء المركبة
  result = result.replace(/\bكاملجابرشمخي\b/g, 'كامل جابر شمخي');
  result = result.replace(/\bكاملجابر\b/g, 'كامل جابر');
  result = result.replace(/\bجابرشمخي\b/g, 'جابر شمخي');
  result = result.replace(/\bحسينكامل\b/g, 'حسين كامل');
  result = result.replace(/\bالعريفحسين\b/g, 'العريف حسين');
  result = result.replace(/\bعريفحسين\b/g, 'عريف حسين');

  // فك دمج المصطلحات الإدارية
  result = result.replace(/\bتاريخانفكاك\b/g, 'تاريخ انفكاك');
  result = result.replace(/\bانفكاكملحق\b/g, 'انفكاك ملحق');
  result = result.replace(/\bمنسوبناالمحال\b/g, 'منسوبنا المحال');
  result = result.replace(/\bالسىالتقاعد\b/g, 'إلى التقاعد');
  result = result.replace(/\bالسيالتقاعد\b/g, 'إلى التقاعد');
  result = result.replace(/\bإلىالتقاعد\b/g, 'إلى التقاعد');
  result = result.replace(/\bلعدمتقيده\b/g, 'لعدم تقيده');
  result = result.replace(/\bبقواعدالسلوك\b/g, 'بقواعد السلوك');
  result = result.replace(/\bالسلوكالمهني\b/g, 'السلوك المهني');

  return result;
}

